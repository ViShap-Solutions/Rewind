using System.Text;
using ViShap.Rewind.Generator.Model;

namespace ViShap.Rewind.Generator;

/// <summary>Prints the source of a <see cref="TypePlan"/>. It decides nothing: every rule is in the planner.</summary>
internal static class RewindEmitter
{
    private const string Write = "global::ViShap.Rewind.Contracts.RewindProperty.Write";

    /// <summary>Returns the source implementing the partial properties of <paramref name="plan"/>.</summary>
    public static string Emit(TypePlan plan)
    {
        var source = new StringBuilder();
        source.Append("// <auto-generated/>\n");
        source.Append("#nullable enable\n");

        var depth = 0;
        if (plan.Namespace is not null)
        {
            source.Append('\n').Append("namespace ").Append(plan.Namespace).Append('\n').Append("{\n");
            depth++;
        }

        foreach (var containing in plan.ContainingTypes)
        {
            Line(source, depth, $"partial {containing.Keyword} {containing.Name}");
            Line(source, depth, "{");
            depth++;
        }

        if (plan.Namespace is null && plan.ContainingTypes.Length == 0)
        {
            source.Append('\n');
        }

        Line(source, depth, $"partial {plan.Declaration.Keyword} {plan.Declaration.Name}");
        Line(source, depth, "{");
        depth++;

        for (var i = 0; i < plan.Properties.Length; i++)
        {
            if (i > 0)
            {
                source.Append('\n');
            }

            Property(source, depth, plan.Properties[i], plan.OwnerName);
        }

        while (depth > 0)
        {
            depth--;
            Line(source, depth, "}");
        }

        return source.ToString();
    }

    private static void Property(StringBuilder source, int depth, PropertyPlan property, string owner)
    {
        var storage = "__rewind" + property.Name;
        var initializer = property.ReferenceLike ? " = default!" : string.Empty;

        Line(source, depth, $"private {property.Type} {storage}{initializer};");
        if (property.Tracked)
        {
            Line(source, depth, $"private long {storage}Epoch;");
            Line(source, depth, $"private static readonly global::System.Action<{owner}, {property.Type}> {storage}Restore = static (owner, value) => owner.{storage} = value;");
        }

        source.Append('\n');
        Line(source, depth, $"{property.Modifiers} {property.Type} {property.Name}");
        Line(source, depth, "{");
        Line(source, depth + 1, $"{Prefix(property.GetterModifiers)}get => {storage};");
        Line(source, depth + 1, property.Tracked
            ? $"{Prefix(property.SetterModifiers)}set => {Write}(this, ref {storage}, ref {storage}Epoch, value, {storage}Restore);"
            : $"{Prefix(property.SetterModifiers)}set => {storage} = value;");
        Line(source, depth, "}");
    }

    private static string Prefix(string modifiers) => modifiers.Length == 0 ? string.Empty : modifiers + " ";

    private static void Line(StringBuilder source, int depth, string text) =>
        source.Append(' ', depth * 4).Append(text).Append('\n');
}
